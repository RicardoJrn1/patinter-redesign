// Regenerates src/lib/logo-morph/logo-paths.ts from the official logo file:
//
//   node scripts/trace-logo.mjs [path/to/logo.png]
//
// Then checks the result: the traced logo is rasterised back at the file's own size and compared with
// the original, pixel by pixel. Run it again whenever the logo file changes (a larger PNG gives finer
// outlines). Node 22.18+ is needed, to import the TypeScript tracer directly.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { traceLogo } from "../src/lib/logo-morph/trace.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.resolve(root, process.argv[2] ?? "src/assets/brand/patinter-logo.png");
const target = path.join(root, "src/lib/logo-morph/logo-paths.ts");

const { data, info } = await sharp(source).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const logo = traceLogo({ width: info.width, height: info.height, data });

const relative = path.relative(root, source).replaceAll("\\", "/");
const generated = `// GENERATED by scripts/trace-logo.mjs from ${relative} — do not edit by hand.
// The official logo, split into its components and traced to vector outlines (see trace.ts).
import type { TracedLogo } from "./trace";

export const LOGO: TracedLogo = ${JSON.stringify(logo, null, 2)};
`;
writeFileSync(target, generated);

// ---- fidelity check: the traced logo, rasterised at the file's size, against the file itself
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${logo.width}" height="${logo.height}" viewBox="0 0 ${logo.width} ${logo.height}">
${logo.stripes.map((s) => `<path fill="${logo.red}" fill-rule="evenodd" d="${s.base}"/><path fill="${logo.yellow}" fill-rule="evenodd" d="${s.yellow}"/>`).join("\n")}
${logo.letters.map((l) => `<path fill="${logo.red}" fill-rule="evenodd" d="${l.path}"/>`).join("\n")}
</svg>`;
const traced = await sharp(Buffer.from(svg)).ensureAlpha().raw().toBuffer();

// compare premultiplied colour (what is actually seen over a background), in 0–255 steps
let sum = 0;
let worst = 0;
let off = 0;
const pixels = info.width * info.height;
for (let i = 0; i < pixels; i++) {
  let diff = 0;
  for (let c = 0; c < 3; c++) {
    const a = (data[i * 4 + c] * data[i * 4 + 3]) / 255;
    const b = (traced[i * 4 + c] * traced[i * 4 + 3]) / 255;
    diff = Math.max(diff, Math.abs(a - b));
  }
  diff = Math.max(diff, Math.abs(data[i * 4 + 3] - traced[i * 4 + 3]));
  sum += diff;
  worst = Math.max(worst, diff);
  if (diff > 64) off++;
}

console.log(`traced ${logo.stripes.length} stripes and ${logo.letters.length} letters → ${path.relative(root, target)}`);
console.log(`colours: red ${logo.red}, yellow ${logo.yellow}; symbol width ${logo.symbolWidth}px`);
console.log(
  `fidelity at ${info.width}×${info.height}: mean difference ${(sum / pixels).toFixed(2)}/255, ` +
    `worst ${worst}/255, ${off} pixels off by more than 25% (${((off / pixels) * 100).toFixed(2)}%)`
);
